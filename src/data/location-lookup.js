/**
 * 嘗試把地點名稱解析成 { lat, lng }，找不到回傳 null。
 * 先做完全字串相符，再嘗試以子字串雙向比對（『八幡坂展望』內含『八幡坂』、
 * 反之亦然），讓使用者輸入時不需精確一致也能查到。
 */
export function lookupLocation(name) {
  if (!name) return null;
  const trimmed = String(name).trim();
  if (!trimmed) return null;

  if (LOCATION_LOOKUP[trimmed]) return LOCATION_LOOKUP[trimmed];

  for (const [key, coords] of Object.entries(LOCATION_LOOKUP)) {
    if (trimmed.includes(key) || key.includes(trimmed)) return coords;
  }
  return null;
}
